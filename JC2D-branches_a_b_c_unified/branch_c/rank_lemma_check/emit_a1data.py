#!/usr/bin/env python3
"""Emit A1 data as Lean, split into 8 modules mirroring RCData.

Why split: a single 3.5 MB A1Data.lean (3199-element lists) was killed by
signal 9 (OOM) after ~29 min of elaboration on this 8 GB, no-swap VM.
RCData's own 8-module split (400 columns each) compiles in ~45 s per module,
so this emitter follows the same shape.

Input: rank_lemma_check/INVERSE.pkl (kept output of build_matrix + make_inverse),
       p = 32003, colv[j] = [(row, value), ...] for pivot column j of M_S.
Output (grade_a/lean/GradeA/):
  A1Data00..07.lean  -- per-module lists colDataPart{k}/cpkPart{k}/xsumPart{k}
  A1Data.lean        -- wrapper: imports the 8 modules, defines colDataNat /
                       CpkFunNat / XSumNat by range dispatch + List.getD
Verification: every xsum element is compared textually against the col_j
statement in the generated RCCheck files; any mismatch aborts the run.
"""
import pickle
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BC = HERE.parent  # branch_c
PKL = HERE / "INVERSE.pkl"
GRADEA = BC / "grade_a" / "lean" / "GradeA"
RCLEAN = HERE / "lean"
K, BLK = 8, 400

d = pickle.load(open(PKL, "rb"))
p, colv = d["p"], d["colv"]
n = len(colv)
assert p == 32003, p
assert n == 3199, n
assert all(0 < v < p for c in colv for _, v in c)
assert all(0 <= i < n for c in colv for i, _ in c)
assert max(len(c) for c in colv) <= 52

# --- verification against the RCCheck col_j statements ---
col_sums = {}
for k in range(K):
    txt = (RCLEAN / f"RCCheck{k:02d}.lean").read_text()
    for m in re.finditer(r"theorem col_(\d+) : colOK \d+ \((.*?)\) = true :=", txt):
        col_sums[int(m.group(1))] = m.group(2)
assert len(col_sums) == 3199, len(col_sums)
bad = 0
for j in range(n):
    arm = " + ".join(f"{v} * Cpk_{i}" for i, v in colv[j])
    if col_sums[j] != arm:
        bad += 1
        if bad <= 3:
            print(f"MISMATCH col {j}", file=sys.stderr)
assert bad == 0, f"{bad} col_j mismatches"

HEADER = """import RCData00
import RCData01
import RCData02
import RCData03
import RCData04
import RCData05
import RCData06
import RCData07

open BranchC.RankCheck

set_option maxHeartbeats 4000000
set_option maxRecDepth 100000

namespace BranchC.A1Data
"""

for k in range(K):
    lo, hi = k * BLK, min(n, (k + 1) * BLK)
    lines = [f"/- A1 data, columns {lo}..{hi - 1} (see emit_a1data.py). -/",
             "", HEADER]
    lines.append(f"def colDataPart{k} : List (List (Nat × Nat)) := [")
    for j in range(lo, hi):
        pairs = ", ".join(f"({i}, {v})" for i, v in colv[j])
        lines.append(f"  [{pairs}],")
    lines.append("]")
    lines.append("")
    lines.append(f"noncomputable def cpkPart{k} : List Nat := [")
    for i in range(lo, hi):
        lines.append(f"  Cpk_{i},")
    lines.append("]")
    lines.append("")
    lines.append(f"noncomputable def xsumPart{k} : List Nat := [")
    for j in range(lo, hi):
        arm = " + ".join(f"{v} * Cpk_{i}" for i, v in colv[j])
        lines.append(f"  {arm},")
    lines.append("]")
    lines.append("")
    lines.append("end BranchC.A1Data")
    lines.append("")
    out = GRADEA / f"A1Data{k:02d}.lean"
    out.write_text("\n".join(lines))
    print(f"wrote {out} ({out.stat().st_size} bytes)")

# --- wrapper with range dispatch ---
w = []
w.append("/- A1 data: pivot-column lists of M_S, as Lean list lookups.")
w.append("")
w.append("    Generated by `rank_lemma_check/emit_a1data.py` from the kept")
w.append("    `INVERSE.pkl` (build_matrix + make_inverse, p = 32003).")
w.append("    - `colDataNat j` is colv[j]: the (row, value) entries of pivot")
w.append("      column j of M_S (at most 52 entries, values < 32003, rows < 3199).")
w.append("    - `CpkFunNat i` is Cpk_i for i < 3199 (0 otherwise), so the packed")
w.append("      columns of C are available as a function of the row index.")
w.append("    - `XSumNat j` is the col_j sum in exactly the form of the RCCheck")
w.append("      `col_j` statements (verified textually against all 3199 of them).")
w.append("    Split into A1Data00..07 (400 columns each): a single 3.5 MB file")
w.append("    was killed (OOM) during elaboration on this VM.")
w.append("-/")
w.append("")
for k in range(K):
    w.append(f"import A1Data{k:02d}")
w.append("")
w.append("namespace BranchC.A1Data")
w.append("")


# Build the dispatch chains explicitly.
def chain(fname, part, typ, dflt, noncomp=False):
    lines = [f"{'noncomputable ' if noncomp else ''}def {fname} (j : Nat) : {typ} :="]
    for k in range(K):
        lo = k * BLK
        hi = min(n, lo + BLK)
        cond = f"j < {hi}" if k < K - 1 else None
        expr = f"{part}{k}.getD (j - {lo}) {dflt}"
        if cond is None:
            lines.append(f"  {expr}")
        elif k == 0:
            lines.append(f"  if {cond} then {expr} else")
        else:
            lines.append(f"  if {cond} then {expr} else")
    return lines


# The chain builder above produces `if ... then ... else` lines whose
# continuation is the next line; Lean accepts this layout.
w.extend(chain("colDataNat", "colDataPart", "List (Nat × Nat)", "[]"))
w.append("")
w.extend(chain("CpkFunNat", "cpkPart", "Nat", "0", noncomp=True))
w.append("")
w.extend(chain("XSumNat", "xsumPart", "Nat", "0", noncomp=True))
w.append("")
w.append("end BranchC.A1Data")
w.append("")
out = GRADEA / "A1Data.lean"
out.write_text("\n".join(w))
print(f"wrote {out} ({out.stat().st_size} bytes); all 3199 XSum arms match RCCheck")
