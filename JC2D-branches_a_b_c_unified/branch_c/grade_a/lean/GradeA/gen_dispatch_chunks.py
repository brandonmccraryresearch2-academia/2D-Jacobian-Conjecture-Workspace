#!/usr/bin/env python3
"""Generate the chunked A1 dispatch files.

Design (see A1Dispatch.lean, superseded: a single full-3199 decide+kernel
OOMs in ~110s even without Mathlib, while single-column kernel checks in
the RC modules are cheap):
- A1DispatchBase.lean: termsFunNat only.
- A1Dispatch{c}.lean (c = 0..7): the six dispatch lemmas restricted to
  columns 400*c .. 400*c+399, each a bounded decide+kernel over
  `forall j : Nat, j < 400 -> ...` (400 kernel evaluations per lemma,
  memory freed between theorems, as in the RC modules).
- A1DispatchAsm.lean: the six full Fin-3199 dispatch lemmas, assembled
  from the chunks by range dispatch (nested by_cases, core-only).
  Names and signatures match the original dispatch section of
  A1Instantiation.lean exactly, so the rest of that file is unchanged.
"""
import os
import sys

SKIP_HX = "--no-hx" in sys.argv

G = os.path.dirname(os.path.abspath(__file__))
OPTS = ("set_option exponentiation.threshold 200000\n"
        "set_option maxRecDepth 1000000\n"
        "set_option maxHeartbeats 4000000\n")

# (chunk lemma name stem, full statement body template, chunk body template)
# {c} = chunk index literal, {j} = bound variable name in chunk lemma.
LEMMAS = [
    ("colThm",
     "BranchC.RankCheck.colOK j.val (XSumNat j.val) = true",
     "BranchC.RankCheck.colOK (400 * {c} + j) (XSumNat (400 * {c} + j)) = true"),
    ("slotThm",
     "BranchC.RankCheck.slotOK (CpkFunNat i.val) = true",
     "BranchC.RankCheck.slotOK (CpkFunNat (400 * {c} + j)) = true"),
    ("coeff_bound",
     "∀ t ∈ colDataNat j.val, t.2 < 32003",
     "∀ t ∈ colDataNat (400 * {c} + j), t.2 < 32003"),
    ("length_bound",
     "(colDataNat j.val).length ≤ 52",
     "(colDataNat (400 * {c} + j)).length ≤ 52"),
    ("row_bound",
     "∀ t ∈ colDataNat j.val, t.1 < 3199",
     "∀ t ∈ colDataNat (400 * {c} + j), t.1 < 3199"),
    ("hX_all",
     "((termsFunNat j.val).map (fun t => t.1 * t.2)).sum = XSumNat j.val",
     "((termsFunNat (400 * {c} + j)).map (fun t => t.1 * t.2)).sum "
     "= XSumNat (400 * {c} + j)"),
]

with open(os.path.join(G, "A1DispatchBase.lean"), "w") as f:
    f.write("""/- A1 dispatch base: termsFunNat only (shared by all chunk files).

    Core-Lean only. Supersedes nothing on its own; A1Dispatch.lean (the
    single full-3199 decide version) is superseded by the chunked files
    generated by gen_dispatch_chunks.py.
-/

import RCCommon
import A1Data

namespace BranchC.A1Inst

open BranchC.A1Data

/-- The (coefficient, packed column) terms for pivot column n. -/
noncomputable def termsFunNat (n : Nat) : List (Nat × Nat) :=
  (colDataNat n).map (fun p => (p.2, CpkFunNat p.1))

end BranchC.A1Inst
""")

for c in range(8):
    bound = min(400, 3199 - 400 * c)
    lo, hi = 400 * c, 400 * c + bound - 1
    with open(os.path.join(G, f"A1Dispatch{c}.lean"), "w") as f:
        f.write(f"""/- A1 dispatch, chunk {c}: columns {lo}..{hi}.

    Core-Lean only. Each lemma is a bounded decide+kernel over 400
    columns, so no single kernel reduction ever covers all 3199 columns
    (the full-3199 version OOMs in ~110s). Generated by
    gen_dispatch_chunks.py; do not hand-edit.
-/

import RCCommon
import A1Data
import A1DispatchBase

{OPTS}
namespace BranchC.A1Inst

open BranchC.A1Data

""")
        for stem, _full, chunk in LEMMAS:
            if SKIP_HX and stem == "hX_all":
                continue
            body = chunk.format(c=c)
            f.write(f"theorem {stem}{c} : ∀ j : Nat, j < {bound} → {body} := by\n"
                    f"  decide +kernel\n\n")
        f.write("end BranchC.A1Inst\n")

# Assembly: full Fin-3199 lemmas from the chunks, CORE-ONLY.
# slotThm is over i : Fin 3199; the rest over j : Fin 3199.
# coeff_bound / row_bound have a membership hypothesis ht to rewrite.
# The case split is nested by_cases on var.val / 400, NOT interval_cases:
# interval_cases times out in whnf on slotThm (4M heartbeats, twice:
# test_asm_slot, test_asm_slot2), while the by_cases shape compiles in
# ~5 s (test_asm_slot_core). Chunk 7's bound (399, column 3199 does not
# exist) is passed as a `(by omega)` term argument.
def asm_lemma(stem, full, var, kind):
    """Full Fin-3199 assembly lemma for one dispatch kind.

    kind "goal": theorem ∀ var : Fin 3199, full.
    kind "mem": theorem ∀ j : Fin 3199, full (full starts with ∀ t ∈ ...),
      with ht rewritten alongside the goal."""
    intro = f"intro {var}" if kind == "goal" else f"intro {var} t ht"
    head = (f"theorem {stem} : ∀ {var} : Fin 3199, {full} := by\n"
            f"  {intro}\n"
            f"  have h{var} : {var}.val < 3199 := {var}.isLt\n"
            f"  have hr : {var}.val % 400 < 400 := Nat.mod_lt _ (by decide)\n"
            f"  have hd : 400 * ({var}.val / 400) + {var}.val % 400 = {var}.val "
            f":= Nat.div_add_mod _ _\n")

    def then_tac(k):
        if kind == "goal":
            return f"rw [← hd, h{k}]; exact {stem}{k} _ hr"
        return f"rw [← hd, h{k}] at ht; exact {stem}{k} _ hr t ht"

    def fin_tac():
        if kind == "goal":
            return f"rw [← hd, h7]; exact {stem}7 _ (by omega)"
        return f"rw [← hd, h7] at ht; exact {stem}7 _ (by omega) t ht"

    def nest(k):
        # Layout must match the passing hand test exactly: the bullets
        # for level k sit at indent 2(k+1) -- the SAME indent as their
        # by_cases line (top level) or as the parent bullet's token
        # column (nested levels). Bullets deeper than their by_cases
        # line are NOT recognized: Lean then parses the next `·` as a
        # term argument ("Function expected ... applied to ·").
        # So nest(k) returns its first line WITHOUT indent (it is placed
        # after "· " by the parent, or after "  " at the top level).
        bind = "  " * (k + 1)
        if k < 6:
            nested = nest(k + 1)
            first, _, rest = nested.partition("\n")
            return (f"by_cases h{k} : {var}.val / 400 = {k}\n"
                    f"{bind}· {then_tac(k)}\n"
                    f"{bind}· {first}\n{rest}")
        fin = "  " * (k + 2)
        return (f"by_cases h{k} : {var}.val / 400 = {k}\n"
                f"{bind}· {then_tac(k)}\n"
                f"{bind}· have h7 : {var}.val / 400 = 7 := by omega\n"
                f"{fin}{fin_tac()}\n")

    return head + "  " + nest(0) + "\n"


with open(os.path.join(G, "A1DispatchAsm.lean"), "w") as f:
    f.write("""/- A1 dispatch assembly: full Fin-3199 lemmas from the 8 chunks.

    Core-Lean only, NO Mathlib: the case split is nested by_cases on
    var.val / 400 (see asm_lemma). Names and signatures match the
    original dispatch section of A1Instantiation.lean exactly.
    Generated by gen_dispatch_chunks.py; do not hand-edit.
-/

import RCCommon
import A1Data
import A1DispatchBase
""")
    for c in range(8):
        f.write(f"import A1Dispatch{c}\n")
    f.write(f"\n{OPTS}\nnamespace BranchC.A1Inst\n\nopen BranchC.A1Data\n\n")
    for stem, full, _chunk in LEMMAS:
        if SKIP_HX and stem == "hX_all":
            continue
        if stem == "slotThm":
            f.write(asm_lemma(stem, full, "i", "goal"))
        elif stem in ("coeff_bound", "row_bound"):
            f.write(asm_lemma(stem, full, "j", "mem"))
        else:
            f.write(asm_lemma(stem, full, "j", "goal"))
    f.write("end BranchC.A1Inst\n")

print("generated: A1DispatchBase, A1Dispatch0..7, A1DispatchAsm")
