#!/usr/bin/env python3
"""Generate the hX dispatch chunks (bound 100) + assembly, core-only.

Why bound 100: hX_all at bound 400 OOMs (~3 min, memory-bound), while
hX at bound 100 passes in 28 s (HX50: 11 s) -- superlinear blowup, so
100 is the proven-safe chunk size. 32 chunks cover columns 0..3198;
chunk 31 has bound 99 (column 3199 does not exist). Assembly is nested
by_cases on j.val / 100, same layout as A1DispatchAsm (bullets at the
same indent as their by_cases line -- see gen_dispatch_chunks.py).
"""
import os

G = os.path.dirname(os.path.abspath(__file__))
OPTS = ("set_option exponentiation.threshold 200000\n"
        "set_option maxRecDepth 1000000\n"
        "set_option maxHeartbeats 4000000\n")

DIV = 100
NCH = 32  # chunks 0..31

# TWO chunk theorems per file, EXCEPT chunks 26/27 (columns 2600..2799),
# which OOM even two-per-file in a clean memory window (killed twice:
# 10m09s, 3m29s) while HX00..HX12 pass at ~1 min each -- so those two
# chunks are genuinely heavier for hX evaluation, and each gets its own
# file. If a single chunk-26/27 file also OOMs, split that chunk to
# bound 50.
FILES = [(f"A1DispatchHX{c // 2:02d}", range(c, c + 2))
         for c in range(0, 26, 2)]
FILES += [("A1DispatchHXc26", [26]), ("A1DispatchHXc27", [27])]
FILES += [(f"A1DispatchHX{c // 2:02d}", range(c, c + 2))
          for c in range(28, 32, 2)]

for fname, cs in FILES:
    with open(os.path.join(G, fname + ".lean"), "w") as f:
        f.write(f"""/- hX dispatch, {fname}: chunk theorems hX100_c.

    Core-Lean only. Each lemma is a bounded decide+kernel over at most
    100 columns (hX at bound 400 OOMs; at bound 100 it passes in ~28 s).
    At most two theorems per file (chunks 26/27 alone: they OOM even
    two-per-file): eight per file OOMs by accumulation across theorems
    in one process. Generated by gen_hx_chunks.py; do not
    hand-edit.
-/

import RCCommon
import A1Data
import A1DispatchBase

{OPTS}
namespace BranchC.A1Inst

open BranchC.A1Data

""")
        for c in cs:
            bound = min(DIV, 3199 - DIV * c)
            f.write(f"theorem hX100_{c} : ∀ j : Nat, j < {bound} → "
                    f"((termsFunNat (100 * {c} + j)).map (fun t => t.1 * t.2)).sum "
                    f"= XSumNat (100 * {c} + j) := by\n"
                    f"  decide +kernel\n\n")
        f.write("end BranchC.A1Inst\n")


def then_tac(k):
    return f"rw [← hd, h{k}]; exact hX100_{k} _ hr"


def fin_tac():
    return "rw [← hd, h31]; exact hX100_31 _ (by omega)"


def nest(k):
    # Same bullet layout as A1DispatchAsm: bullets at indent 2(k+1),
    # first line without indent (placed after "· " by the parent).
    bind = "  " * (k + 1)
    if k < 30:
        nested = nest(k + 1)
        first, _, rest = nested.partition("\n")
        return (f"by_cases h{k} : j.val / 100 = {k}\n"
                f"{bind}· {then_tac(k)}\n"
                f"{bind}· {first}\n{rest}")
    fin = "  " * (k + 2)
    return (f"by_cases h{k} : j.val / 100 = {k}\n"
            f"{bind}· {then_tac(k)}\n"
            f"{bind}· have h31 : j.val / 100 = 31 := by omega\n"
            f"{fin}{fin_tac()}\n")


asm = ("theorem hX_all : ∀ j : Fin 3199, "
       "((termsFunNat j.val).map (fun t => t.1 * t.2)).sum = XSumNat j.val := by\n"
       "  intro j\n"
       "  have hj : j.val < 3199 := j.isLt\n"
       "  have hr : j.val % 100 < 100 := Nat.mod_lt _ (by decide)\n"
       "  have hd : 100 * (j.val / 100) + j.val % 100 = j.val := Nat.div_add_mod _ _\n"
       "  " + nest(0) + "\n")

with open(os.path.join(G, "A1DispatchHXAsm.lean"), "w") as f:
    f.write("""/- hX dispatch assembly: full Fin-3199 hX_all from the 32 chunks.

    Core-Lean only, NO Mathlib: nested by_cases on j.val / 100.
    Generated by gen_hx_chunks.py; do not hand-edit.
-/

import RCCommon
import A1Data
import A1DispatchBase
""")
    for fname, _cs in FILES:
        f.write(f"import {fname}\n")
    f.write(f"\n{OPTS}\nnamespace BranchC.A1Inst\n\nopen BranchC.A1Data\n\n")
    f.write(asm)
    f.write("end BranchC.A1Inst\n")

print("generated: A1DispatchHX00..12, HXc26, HXc27, HX14, HX15, A1DispatchHXAsm")
