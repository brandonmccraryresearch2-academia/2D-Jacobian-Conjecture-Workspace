# 1. Docstring: interval_cases/Mathlib -> by_cases/core-only.
src = src.replace(
    "  from the chunks by range dispatch (set + interval_cases, Mathlib).",
    "  from the chunks by range dispatch (nested by_cases, core-only).")

# 2. Remove the now-unused chain() helper.
i = src.index('def chain(stem, var, extra=""):')
